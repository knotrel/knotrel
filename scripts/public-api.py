def rustdoc_json(package: str, crate_name: str, features: list[str], target_dir: str) -> dict:
    """Builds rustdoc JSON for one package with the given features."""
    env = dict(os.environ, RUSTC_BOOTSTRAP="1", CARGO_TARGET_DIR=target_dir)
    cmd = ["cargo", "rustdoc", "--quiet", "--locked", "-p", package, "--lib"]
    if features:
        cmd += ["--features", ",".join(features)]
    cmd += ["--", "-Z", "unstable-options", "--output-format", "json"]
    subprocess.run(cmd, cwd=ROOT, env=env, check=True)
    with open(os.path.join(target_dir, "doc", f"{crate_name}.json"), encoding="utf-8") as handle:
        return json.load(handle)


@dataclass
class Snapshot:
    """The rendered public API of one crate across its feature sets."""

    crate: str
    lines: list[str] = field(default_factory=list)
    # path -> (parent path, feature or None)
    items: dict[str, tuple[str | None, str | None]] = field(default_factory=dict)
    # Canonical path -> public path, for crates that depend on this one.
    aliases: dict[str, str] = field(default_factory=dict)


def build_snapshot(
    crate_name: str, docs: list[tuple[str | None, dict]], aliases: dict[str, str] | None = None
) -> Snapshot:
    """Merges the renderings of one crate's feature sets into a snapshot.

    ``docs`` holds (feature, rustdoc JSON) pairs, the default set first with
    feature ``None``. An entry missing from the default set is marked with
    the cfg of the first feature set that has it; an entry that disappears
    when a feature is enabled is an error (features must be additive).
    """
    snapshot = Snapshot(crate_name)
    # key -> (entry, cfg prefix)
    seen: dict[str, tuple[Entry, str]] = {}
    default_keys: set[str] = set()
    for position, (feature, doc) in enumerate(docs):
        keys = set()
        renderer = Renderer(doc, aliases)
        for entry in renderer.render(crate_name):
            key = entry.sort_key + "\0" + entry.text
            keys.add(key)
            if key not in seen:
                seen[key] = (entry, f'#[cfg(feature = "{feature}")] ' if feature else "")
        if position == 0:
            default_keys = keys
            snapshot.aliases = renderer.public_aliases()
            continue
        # Features should be additive, but auto traits can disappear (a
        # feature adds a field that is not UnwindSafe, say). Record that.
        for key in default_keys - keys:
            entry, prefix = seen[key]
            if entry.path is not None:
                raise SystemExit(f"{crate_name}: {entry.path} disappears with feature {feature!r}")
            seen[key] = (entry, f'#[cfg(not(feature = "{feature}"))] ' + prefix)
    for key in sorted(seen):
        entry, prefix = seen[key]
        snapshot.lines.append(prefix + entry.text)
        if entry.path is not None:
            feature = re.match(r'#\[cfg\(feature = "([^"]+)"\)\]', prefix)
            snapshot.items.setdefault(entry.path, (entry.parent, feature.group(1) if feature else None))
    return snapshot


def snapshot_file(crate_name: str) -> str:
    return os.path.join(API_DIR, f"public-api-{crate_name.replace('_', '-')}.txt")


def render_file(snapshot: Snapshot) -> str:
    return GENERATED_HEADER + "".join(line + "\n" for line in snapshot.lines)


def generate_all(target_dir: str) -> list[Snapshot]:
    snapshots = []
    aliases: dict[str, str] = {}
    for package, crate_name, extra in CRATES:
        docs = [(None, rustdoc_json(package, crate_name, [], target_dir))]
        for feature in extra:
            docs.append((feature, rustdoc_json(package, crate_name, [feature], target_dir)))
        snapshot = build_snapshot(crate_name, docs, aliases)
        aliases.update(snapshot.aliases)
        snapshots.append(snapshot)
    return snapshots


