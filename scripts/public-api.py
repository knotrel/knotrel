CLASS_LINE = re.compile(r"^(stable|experimental|internal)\s+([A-Za-z0-9_:]+)\s*$")


def parse_classification(text: str) -> tuple[dict[str, str], list[str]]:
    """Parses ``<class> <path>`` lines; returns (classes, errors)."""
    classes: dict[str, str] = {}
    errors = []
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        match = CLASS_LINE.match(line)
        if not match:
            errors.append(f"classification line {number}: expected '<stable|experimental|internal> <path>', got {raw!r}")
            continue
        cls, path = match.groups()
        if path in classes:
            errors.append(f"classification line {number}: {path} is classified twice")
        classes[path] = cls
    return classes, errors


def check_classification(items: dict[str, tuple[str | None, str | None]], classes: dict[str, str]) -> list[str]:
    """Every named item is classified exactly; the classes are consistent.

    Rules: no public item without a class; no class for a path that is not a
    public item; a member never has a higher class than its parent
    (stable > experimental > internal); items that exist only behind a
    test-instrumentation feature are internal.
    """
    errors = []
    for path in sorted(set(items) - set(classes)):
        errors.append(f"unclassified public item: {path} (add it to docs/api/public-api-classification.txt)")
    for path in sorted(set(classes) - set(items)):
        errors.append(f"classification names no public item: {path}")
    for path, (parent, feature) in sorted(items.items()):
        cls = classes.get(path)
        if cls is None:
            continue
        if parent is not None and parent in classes and RANK[cls] > RANK[classes[parent]]:
            errors.append(f"{path} is {cls} but its parent {parent} is {classes[parent]}")
        if feature in INTERNAL_FEATURES and cls != "internal":
            errors.append(f"{path} exists only with feature {feature!r} and must be internal, not {cls}")
    return errors


