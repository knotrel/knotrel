CLASS_LINE = re.compile(r"^(stable|experimental|internal)\s+(\S.*?)\s*$")
PATH_KEY = re.compile(r"^[A-Za-z0-9_]+(::[A-Za-z0-9_]+)*$")
# Implementations of these traits cannot be named or relied on with stable
# Rust (unstable marker and auto traits): they are always internal.
UNSTABLE_TRAITS = {
    "core::clone::TrivialClone",
    "core::marker::Freeze",
    "core::marker::StructuralPartialEq",
    "core::marker::UnsafeUnpin",
}


def impl_trait(key: str) -> str:
    """The trait path of an implementation key, without `!` and generics."""
    trait = key[len("impl "):].split(" for ", 1)[0].lstrip("!")
    return trait.split("<", 1)[0]


def parse_classification(text: str) -> tuple[dict[str, str], list[str]]:
    """Parses ``<class> <key>`` lines; returns (classes, errors)."""
    classes: dict[str, str] = {}
    errors = []
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        match = CLASS_LINE.match(line)
        key = match.group(2) if match else ""
        if not match or not (PATH_KEY.match(key) or (is_impl(key) and " for " in key)):
            errors.append(
                f"classification line {number}: expected '<stable|experimental|internal> <path or impl key>', got {raw!r}"
            )
            continue
        if key in classes:
            errors.append(f"classification line {number}: {key} is classified twice")
        classes[key] = match.group(1)
    return classes, errors


def check_classification(items: dict[str, tuple[str | None, str | None]], classes: dict[str, str]) -> list[str]:
    """Every item and implementation is classified exactly; classes are consistent.

    Rules: no public item or trait implementation without a class; no class
    for a key that is not in the snapshot; a member or implementation never
    has a higher class than its parent (stable > experimental > internal);
    items that exist only behind a test-instrumentation feature are internal;
    implementations of unstable traits (``UNSTABLE_TRAITS``) are internal.
    """
    errors = []
    for key in sorted(set(items) - set(classes)):
        kind = "trait implementation" if is_impl(key) else "public item"
        errors.append(f"unclassified {kind}: {key} (add it to docs/api/public-api-classification.txt)")
    for key in sorted(set(classes) - set(items)):
        errors.append(f"classification names no public item: {key}")
    for key, (parent, feature) in sorted(items.items()):
        cls = classes.get(key)
        if cls is None:
            continue
        if parent is not None and parent in classes and RANK[cls] > RANK[classes[parent]]:
            errors.append(f"{key} is {cls} but its parent {parent} is {classes[parent]}")
        if feature in INTERNAL_FEATURES and cls != "internal":
            errors.append(f"{key} exists only with feature {feature!r} and must be internal, not {cls}")
        if is_impl(key) and impl_trait(key) in UNSTABLE_TRAITS and cls != "internal":
            errors.append(f"{key} implements an unstable trait and must be internal, not {cls}")
    return errors


