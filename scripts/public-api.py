#!/usr/bin/env python3
"""Checked public Rust API snapshot and stability classification.

Implements maintainer decision 9 of the v1.0 contract freeze
(docs/releases/v1.0-contract-freeze-review.md, R11): the public API of
`knotrel-core` and `knotrel-server` is committed as a text snapshot, and every
public item, trait implementations included, carries an explicit,
machine-checkable classification.

Files (all under docs/api/ unless noted):

* ``public-api-<crate>.txt`` (generated): one line per public item and per
  non-blanket trait implementation, rendered from rustdoc JSON (hidden items
  included). Items that exist only with the ``test-support`` feature are
  prefixed with ``#[cfg(feature = "test-support")]``.
* ``public-api-classification.txt`` (maintained by hand): one line per public
  item, ``<class> <key>``; class is ``stable``, ``experimental`` or
  ``internal``; the key is the item's path, or ``impl <Trait> for <Type>``
  for a trait implementation.
* ``public-api-policy.toml`` (maintained by hand, reviewed separately): the
  approved ``#[non_exhaustive]`` items, the approved narrowings (stable items
  made experimental, internal or removed) and the approved, per-release
  cargo-semver-checks lint exceptions.
* ``docs/stability.md``: its two Rust tables are cross-checked against the
  classification (see ``check_stability``).

Subcommands:

* ``generate``: rebuild rustdoc JSON and rewrite the snapshots.
* ``check``: rebuild rustdoc JSON and run every check of ``run_checks``; with
  a base revision (``--base``, or the pull request's base in CI), also
  compare the classification with the base's (``check_narrowing``).

rustdoc JSON is an unstable rustdoc output. The script enables it on the
pinned workspace toolchain (rust-toolchain.toml) with ``RUSTC_BOOTSTRAP=1``,
for this one rustdoc invocation only, as cargo-semver-checks does; the
format version is checked so a toolchain change fails loudly instead of
producing a silently different snapshot. Only the standard library is used
(``tomllib`` needs Python 3.11).
"""

