# Policy: non_exhaustive, narrowings, semver-checks exceptions
# ---------------------------------------------------------------------------


@dataclass
class Policy:
    """The separately reviewed decisions of ``public-api-policy.toml``."""

    non_exhaustive: set[str] = field(default_factory=set)
    # (key, from class, to class or "removed")
    narrowings: set[tuple[str, str, str]] = field(default_factory=set)
    semver_exceptions: list[dict] = field(default_factory=list)


def parse_policy(text: str) -> tuple[Policy, list[str]]:
    """Parses and validates the policy file; returns (policy, errors)."""
    policy = Policy()
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as error:
        return policy, [f"public-api-policy.toml: {error}"]
    errors = []
    policy.non_exhaustive = set(data.get("non_exhaustive", {}).get("items", []))
    for number, entry in enumerate(data.get("narrowing", []), 1):
        missing = [k for k in ("item", "from", "to", "release", "reason") if not entry.get(k)]
        before, after = entry.get("from"), entry.get("to")
        if missing:
            errors.append(f"public-api-policy.toml: narrowing #{number} lacks {', '.join(missing)}")
        elif before not in CLASSES or (after != "removed" and (after not in CLASSES or RANK[after] >= RANK[before])):
            errors.append(f"public-api-policy.toml: narrowing #{number} ({entry['item']}: {before} -> {after}) is not a narrowing")
        else:
            policy.narrowings.add((entry["item"], before, after))
    for number, entry in enumerate(data.get("semver_exception", []), 1):
        missing = [k for k in ("crate", "lints", "until", "items", "decision") if not entry.get(k)]
        if missing:
            errors.append(f"public-api-policy.toml: semver_exception #{number} lacks {', '.join(missing)}")
        elif version_tuple(entry["until"]) is None:
            errors.append(f"public-api-policy.toml: semver_exception #{number} has an invalid version {entry['until']!r}")
        else:
            policy.semver_exceptions.append(entry)
    return policy, errors


def check_non_exhaustive(found: set[str], policy: Policy) -> list[str]:
    """`#[non_exhaustive]` appears exactly on the approved items.

    cargo-semver-checks lint exceptions apply to a whole crate, so this is
    what keeps the types frozen exhaustive (and the approved ones
    non-exhaustive): adding or removing the attribute anywhere else fails.
    """
    errors = []
    for key in sorted(found - policy.non_exhaustive):
        errors.append(f"{key} is #[non_exhaustive] without approval in docs/api/public-api-policy.toml")
    for key in sorted(policy.non_exhaustive - found):
        errors.append(f"{key} is approved as #[non_exhaustive] in docs/api/public-api-policy.toml but is not")
    return errors


def check_narrowing(base: dict[str, str] | None, classes: dict[str, str], policy: Policy) -> list[str]:
    """No stable item or implementation is narrowed without an approved entry.

    Compared with the base revision's classification (when there is one),
    every key that was stable and is now experimental, internal or gone needs
    a matching ``[[narrowing]]`` entry. Independently of the base, every
    entry must describe the current state, so an entry cannot be left behind
    to excuse a later change.
    """
    errors = []
    if base is not None:
        for key, before in sorted(base.items()):
            after = classes.get(key, "removed")
            if before == "stable" and after != "stable" and (key, before, after) not in policy.narrowings:
                errors.append(
                    f"{key} was stable at the base and is now {after}: a narrowing needs an approved "
                    "[[narrowing]] entry in docs/api/public-api-policy.toml (docs/stability.md lists it separately)"
                )
    for key, before, after in sorted(policy.narrowings):
        current = classes.get(key, "removed")
        if current != after:
            errors.append(f"narrowing entry {key} ({before} -> {after}) does not match its current class {current}")
    return errors


def version_tuple(version: str) -> tuple[int, int, int] | None:
    """Major, minor, patch of a version; a pre-release counts as its release."""
    match = re.match(r"^v?(\d+)\.(\d+)\.(\d+)", version)
    return tuple(int(part) for part in match.groups()) if match else None


def check_semver_exceptions(policy: Policy, crate_lints: dict[str, dict], workspace_version: str) -> list[str]:
    """Every cargo-semver-checks lint exception is approved and not expired.

    A lint configured in a crate's ``[package.metadata.cargo-semver-checks.lints]``
    needs a ``[[semver_exception]]`` entry naming the crate, the lint, the
    items and the release (``until``) that ships the change; an entry without
    its lint in Cargo.toml is stale; and once the workspace version is past
    ``until``, the exception must be removed. A crate-wide exception could
    otherwise hide the removal of a stable item; the snapshot and
    ``check_narrowing`` stay the per-item guard while it exists.
    """
    errors = []
    current = version_tuple(workspace_version)
    for crate, lints in sorted(crate_lints.items()):
        for lint in sorted(lints):
            if not any(e["crate"] == crate and lint in e["lints"] for e in policy.semver_exceptions):
                errors.append(f"{crate}: cargo-semver-checks lint {lint!r} has no [[semver_exception]] in docs/api/public-api-policy.toml")
    for entry in policy.semver_exceptions:
        for lint in entry["lints"]:
            if lint not in crate_lints.get(entry["crate"], {}):
                errors.append(f"{entry['crate']}: [[semver_exception]] for {lint!r} is stale (not in its Cargo.toml)")
        if current is not None and current > version_tuple(entry["until"]):
            errors.append(
                f"{entry['crate']}: the cargo-semver-checks exception {entry['lints']} was for v{entry['until']} and the "
                f"workspace is at {workspace_version}: remove it from crates/{entry['crate']}/Cargo.toml and docs/api/public-api-policy.toml"
            )
    return errors


