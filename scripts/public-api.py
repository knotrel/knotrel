def impl_key(trait: str, for_type: str) -> str:
    """Classification key of a trait implementation.

    ``trait`` is the rendered trait path with its generic arguments, prefixed
    with ``!`` for a negative (auto-trait) implementation; the implementation's
    own generic parameters and where-clauses are not part of the key.
    """
    return f"impl {trait} for {for_type}"


def is_impl(key: str) -> bool:
    """Whether a classification key names a trait implementation."""
    return key.startswith("impl ")


@dataclass(frozen=True)
class Entry:
    """One snapshot line.

    ``path`` is the item's public path for named items and the key
    ``impl <Trait> for <Type>`` (see ``impl_key``) for trait implementations;
    ``parent`` is the path of the enclosing item (the type of a method, field,
    variant or implementation), or ``None`` at the crate root.
    """

    sort_key: str
    text: str
    path: str | None
    parent: str | None


class Renderer:
    """Renders the public items of one rustdoc JSON crate as snapshot entries.

    The walk starts at the crate root and follows public modules and
    re-exports, so an item appears under each public path that reaches it;
    private modules are never named. Types render with their canonical paths
    from the JSON ``paths`` table, so a snapshot does not depend on how a
    signature spells a type. Cost: linear in the size of the JSON document.
    """

    def __init__(self, doc: dict, aliases: dict[str, str] | None = None):
        version = doc.get("format_version")
        if version not in SUPPORTED_FORMATS:
            raise SystemExit(
                f"unsupported rustdoc JSON format {version}; expected one of "
                f"{sorted(SUPPORTED_FORMATS)} (toolchain changed? update the renderer)"
            )
        self.doc = doc
        self.index = doc["index"]
        self.paths = doc["paths"]
        self.entries: list[Entry] = []
        self.visited: set[tuple[str, str]] = set()
        self.public: dict[str, str] = {}
        # Canonical path -> public path of items of other workspace crates.
        self.aliases = aliases or {}

    def collect(self, item, path: str):
        """Records the shortest public path of every local item (pre-pass)."""
        current = self.public.get(str(item["id"]))
        if current is not None and len(current) <= len(path):
            return
        self.public[str(item["id"])] = path
        if "module" not in item["inner"]:
            return
        for child_id in item["inner"]["module"]["items"]:
            child = self.index[str(child_id)]
            if child["visibility"] != "public":
                continue
            if "use" in child["inner"]:
                use = child["inner"]["use"]
                target = self.index.get(str(use["id"])) if use.get("id") is not None else None
                if target is None:
                    continue
                if use["is_glob"]:
                    self.collect_glob(target, path)
                else:
                    self.collect(target, f"{path}::{use['name']}")
            elif child.get("name"):
                self.collect(child, f"{path}::{child['name']}")

    def collect_glob(self, module, path: str):
        for gid in module["inner"].get("module", {}).get("items", []):
            child = self.index[str(gid)]
            if child["visibility"] == "public" and child.get("name") and "use" not in child["inner"]:
                self.collect(child, f"{path}::{child['name']}")

    # -- types --------------------------------------------------------------

    def path_of(self, path: dict) -> str:
        key = str(path.get("id"))
        known = self.paths.get(key)
        if key in self.public:
            name = self.public[key]
        elif known:
            canonical = "::".join(known["path"])
            name = self.aliases.get(canonical, canonical)
        else:
            name = path["path"]
        return name + self.generic_args(path.get("args"))

    def generic_args(self, args) -> str:
        if not args:
            return ""
        if "angle_bracketed" in args:
            inner = args["angle_bracketed"]
            parts = [self.generic_arg(arg) for arg in inner["args"]]
            parts += [self.constraint(c) for c in inner["constraints"]]
            return f"<{', '.join(parts)}>" if parts else ""
        if "parenthesized" in args:
            inner = args["parenthesized"]
            inputs = ", ".join(self.ty(t) for t in inner["inputs"])
            output = inner.get("output")
            return f"({inputs})" + (f" -> {self.ty(output)}" if output else "")
        if args == "return_type_notation":
            return "(..)"
        raise ValueError(f"unknown generic args {args!r}")

    def generic_arg(self, arg) -> str:
        if arg == "infer":
            return "_"
        if "lifetime" in arg:
            return arg["lifetime"]
        if "type" in arg:
            return self.ty(arg["type"])
        if "const" in arg:
            return arg["const"].get("expr") or "_"
        raise ValueError(f"unknown generic arg {arg!r}")

    def constraint(self, c) -> str:
        name = c["name"] + self.generic_args(c.get("args"))
        binding = c["binding"]
        if "equality" in binding:
            term = binding["equality"]
            value = self.ty(term["type"]) if "type" in term else term["constant"].get("expr", "_")
            return f"{name} = {value}"
        return f"{name}: {self.bounds(binding['constraint'])}"

    def bounds(self, bounds) -> str:
        return " + ".join(self.bound(b) for b in bounds)

    def bound(self, b) -> str:
        if "trait_bound" in b:
            tb = b["trait_bound"]
            prefix = {"none": "", "maybe": "?", "maybe_const": "~const "}.get(tb.get("modifier", "none"), "")
            hrtb = self.hrtb(tb.get("generic_params", []))
            return f"{hrtb}{prefix}{self.path_of(tb['trait'])}"
        if "outlives" in b:
            return b["outlives"]
        if "use" in b:
            return "use<" + ", ".join(
                (u.get("lifetime") or u.get("param") or "?") if isinstance(u, dict) else str(u)
                for u in b["use"]
            ) + ">"
        raise ValueError(f"unknown bound {b!r}")

    def hrtb(self, params) -> str:
        names = [p["name"] for p in params]
        return f"for<{', '.join(names)}> " if names else ""

    def ty(self, t) -> str:
        if t is None:
            return "()"
        (kind, value), = t.items()
        if kind == "resolved_path":
            return self.path_of(value)
        if kind == "generic":
            return value
        if kind == "primitive":
            return value
        if kind == "tuple":
            return "(" + ", ".join(self.ty(x) for x in value) + ("," if len(value) == 1 else "") + ")"
        if kind == "slice":
            return f"[{self.ty(value)}]"
        if kind == "array":
            return f"[{self.ty(value['type'])}; {value['len']}]"
        if kind == "borrowed_ref":
            lifetime = f"{value['lifetime']} " if value.get("lifetime") else ""
            mutable = "mut " if value["is_mutable"] else ""
            return f"&{lifetime}{mutable}{self.ty(value['type'])}"
        if kind == "raw_pointer":
            return f"*{'mut' if value['is_mutable'] else 'const'} {self.ty(value['type'])}"
        if kind == "impl_trait":
            return f"impl {self.bounds(value)}"
        if kind == "dyn_trait":
            traits = [self.hrtb(p.get("generic_params", [])) + self.path_of(p["trait"]) for p in value["traits"]]
            if value.get("lifetime"):
                traits.append(value["lifetime"])
            return "dyn " + " + ".join(traits)
        if kind == "function_pointer":
            sig = value["sig"]
            inputs = ", ".join(self.ty(arg) for _, arg in sig["inputs"])
            out = f" -> {self.ty(sig['output'])}" if sig.get("output") else ""
            return f"{self.hrtb(value.get('generic_params', []))}fn({inputs}){out}"
        if kind == "qualified_path":
            self_ty = self.ty(value["self_type"])
            trait = value.get("trait")
            base = f"<{self_ty} as {self.path_of(trait)}>" if trait else self_ty
            return f"{base}::{value['name']}{self.generic_args(value.get('args'))}"
        if kind == "infer":
            return "_"
        if kind == "pat":
            return self.ty(value["type"])
        raise ValueError(f"unknown type kind {kind!r}")

    def generics(self, g) -> tuple[str, str]:
        params = []
        for p in g["params"]:
            (kind, value), = p["kind"].items()
            if kind == "lifetime":
                outlives = value.get("outlives") or []
                params.append(p["name"] + (f": {' + '.join(outlives)}" if outlives else ""))
            elif kind == "type":
                if value.get("is_synthetic"):
                    continue
                text = p["name"]
                if value.get("bounds"):
                    text += f": {self.bounds(value['bounds'])}"
                if value.get("default"):
                    text += f" = {self.ty(value['default'])}"
                params.append(text)
            elif kind == "const":
                params.append(f"const {p['name']}: {self.ty(value['type'])}")
        where = []
        for w in g["where_predicates"]:
            (kind, value), = w.items()
            if kind == "bound_predicate":
                where.append(
                    f"{self.hrtb(value.get('generic_params', []))}{self.ty(value['type'])}: {self.bounds(value['bounds'])}"
                )
            elif kind == "lifetime_predicate":
                where.append(f"{value['lifetime']}: {' + '.join(value['outlives'])}")
            elif kind == "eq_predicate":
                rhs = value["rhs"]
                rhs_text = self.ty(rhs["type"]) if "type" in rhs else rhs["constant"].get("expr", "_")
                where.append(f"{self.ty(value['lhs'])} = {rhs_text}")
        return (f"<{', '.join(params)}>" if params else "", f" where {', '.join(where)}" if where else "")

    # -- items --------------------------------------------------------------

    @staticmethod
    def attrs(item) -> str:
        out = []
        for attr in item.get("attrs", []):
            if attr == "non_exhaustive":
                out.append("#[non_exhaustive]")
            elif isinstance(attr, dict) and "repr" in attr:
                repr_ = attr["repr"]
                parts = [repr_["kind"]] if repr_.get("kind") not in (None, "rust") else []
                if repr_.get("int"):
                    parts.append(repr_["int"])
                if repr_.get("align"):
                    parts.append(f"align({repr_['align']})")
                if repr_.get("packed"):
                    parts.append(f"packed({repr_['packed']})")
                if parts:
                    out.append(f"#[repr({', '.join(parts)})]")
        if item.get("deprecation"):
            out.append("#[deprecated]")
        return "".join(a + " " for a in out)

    def add(self, path: str | None, parent: str | None, text: str, sort_key: str | None = None):
        self.entries.append(Entry(sort_key or path or text, text, path, parent))

    def function(self, item, path: str, parent: str | None, *, method: bool):
        f = item["inner"]["function"]
        header = f["header"]
        quals = "".join(
            q for q, on in (("const ", header["is_const"]), ("async ", header["is_async"]), ("unsafe ", header["is_unsafe"]))
            if on
        )
        params, where = self.generics(f["generics"])
        inputs = []
        for name, t in f["sig"]["inputs"]:
            if method and name == "self":
                if t == {"generic": "Self"}:
                    inputs.append("self")
                    continue
                if "borrowed_ref" in t and t["borrowed_ref"]["type"] == {"generic": "Self"}:
                    ref = t["borrowed_ref"]
                    lifetime = f"{ref['lifetime']} " if ref.get("lifetime") else ""
                    inputs.append(f"&{lifetime}{'mut ' if ref['is_mutable'] else ''}self")
                    continue
            inputs.append(f"{name}: {self.ty(t)}")
        output = f["sig"].get("output")
        ret = f" -> {self.ty(output)}" if output is not None else ""
        self.add(path, parent, f"{self.attrs(item)}pub {quals}fn {path}{params}({', '.join(inputs)}){ret}{where}")

    def struct_fields(self, ids, path: str, tuple_like: bool):
        for position, fid in enumerate(ids):
            if fid is None:
                continue
            fitem = self.index[str(fid)]
            name = str(position) if tuple_like else fitem["name"]
            fpath = f"{path}::{name}"
            self.add(fpath, path, f"pub {fpath}: {self.ty(fitem['inner']['struct_field'])}")

    def impls(self, impl_ids, type_path: str):
        for iid in impl_ids:
            impl_item = self.index.get(str(iid))
            if impl_item is None:
                continue
            impl = impl_item["inner"]["impl"]
            if impl.get("blanket_impl") is not None:
                continue
            if impl["trait"] is None:
                for member_id in impl["items"]:
                    member = self.index[str(member_id)]
                    if member["visibility"] != "public":
                        continue
                    self.member(member, f"{type_path}::{member['name']}", type_path)
                continue
            params, where = self.generics(impl["generics"])
            neg = "!" if impl.get("is_negative") else ""
            unsafe = "unsafe " if impl.get("is_unsafe") else ""
            trait = self.path_of(impl["trait"])
            for_type = self.ty(impl["for"])
            text = f"{unsafe}impl{params} {neg}{trait} for {for_type}{where}"
            self.add(impl_key(neg + trait, for_type), type_path, text, sort_key=f"{type_path} ~impl {trait} {text}")

    def member(self, item, path: str, parent: str):
        (kind, value), = item["inner"].items()
        if kind == "function":
            self.function(item, path, parent, method=True)
        elif kind == "assoc_const":
            val = f" = {value['value']}" if value.get("value") not in (None, "_") else ""
            self.add(path, parent, f"{self.attrs(item)}pub const {path}: {self.ty(value['type'])}{val}")
        elif kind == "assoc_type":
            bound = f": {self.bounds(value['bounds'])}" if value.get("bounds") else ""
            ty = f" = {self.ty(value['type'])}" if value.get("type") else ""
            self.add(path, parent, f"pub type {path}{bound}{ty}")
        else:
            raise ValueError(f"unknown member kind {kind!r} at {path}")

    def item(self, item, path: str, parent: str | None):
        key = (str(item["id"]), path)
        if key in self.visited:
            return
        self.visited.add(key)
        (kind, value), = item["inner"].items()
        attrs = self.attrs(item)
        if kind == "module":
            if not value.get("is_crate"):
                self.add(path, parent, f"pub mod {path}")
            for child_id in value["items"]:
                child = self.index[str(child_id)]
                if child["visibility"] != "public":
                    continue
                self.child(child, path)
        elif kind == "struct":
            params, where = self.generics(value["generics"])
            skind = value["kind"]
            if skind == "unit":
                self.add(path, parent, f"{attrs}pub struct {path}{params}{where};")
            elif "plain" in skind:
                private = " { /* private fields */ }" if skind["plain"]["has_stripped_fields"] else ""
                self.add(path, parent, f"{attrs}pub struct {path}{params}{where}{private}")
                self.struct_fields(skind["plain"]["fields"], path, False)
            else:
                shape = ", ".join(
                    "_" if fid is None else "pub " + self.ty(self.index[str(fid)]["inner"]["struct_field"])
                    for fid in skind["tuple"]
                )
                self.add(path, parent, f"{attrs}pub struct {path}{params}({shape}){where};")
                self.struct_fields(skind["tuple"], path, True)
            self.impls(value["impls"], path)
        elif kind == "enum":
            params, where = self.generics(value["generics"])
            hidden = " { /* hidden variants */ }" if value.get("has_stripped_variants") else ""
            self.add(path, parent, f"{attrs}pub enum {path}{params}{where}{hidden}")
            for vid in value["variants"]:
                self.variant(self.index[str(vid)], path)
            self.impls(value["impls"], path)
        elif kind == "function":
            self.function(item, path, parent, method=False)
        elif kind == "type_alias":
            params, where = self.generics(value["generics"])
            self.add(path, parent, f"{attrs}pub type {path}{params}{where} = {self.ty(value['type'])}")
        elif kind == "constant":
            const = value["const"]
            val = f" = {const.get('value') or const.get('expr')}" if (const.get("value") or const.get("expr")) not in (None, "_") else ""
            self.add(path, parent, f"pub const {path}: {self.ty(value['type'])}{val}")
        elif kind == "static":
            mutable = "mut " if value.get("is_mutable") else ""
            self.add(path, parent, f"pub static {mutable}{path}: {self.ty(value['type'])}")
        elif kind == "trait":
            params, where = self.generics(value["generics"])
            unsafe = "unsafe " if value.get("is_unsafe") else ""
            supertraits = f": {self.bounds(value['bounds'])}" if value.get("bounds") else ""
            self.add(path, parent, f"{attrs}pub {unsafe}trait {path}{params}{supertraits}{where}")
            for member_id in value["items"]:
                member = self.index[str(member_id)]
                self.member(member, f"{path}::{member['name']}", path)
        elif kind in ("macro", "proc_macro"):
            self.add(path, parent, f"pub macro {path}!")
        else:
            raise ValueError(f"unsupported public item kind {kind!r} at {path}")

    def variant(self, item, enum_path: str):
        value = item["inner"]["variant"]
        path = f"{enum_path}::{item['name']}"
        vkind = value["kind"]
        disc = f" = {value['discriminant']['value']}" if value.get("discriminant") else ""
        if vkind == "plain":
            self.add(path, enum_path, f"{self.attrs(item)}pub {path}{disc}")
        elif "tuple" in vkind:
            shape = ", ".join(
                "_" if fid is None else self.ty(self.index[str(fid)]["inner"]["struct_field"])
                for fid in vkind["tuple"]
            )
            self.add(path, enum_path, f"{self.attrs(item)}pub {path}({shape}){disc}")
            self.struct_fields(vkind["tuple"], path, True)
        else:
            hidden = ", .." if vkind["struct"]["has_stripped_fields"] else ""
            names = ", ".join(self.index[str(f)]["name"] for f in vkind["struct"]["fields"])
            self.add(path, enum_path, f"{self.attrs(item)}pub {path} {{ {names}{hidden} }}{disc}")
            self.struct_fields(vkind["struct"]["fields"], path, False)

    def child(self, child, module_path: str):
        if "use" in child["inner"]:
            use = child["inner"]["use"]
            target = self.index.get(str(use["id"])) if use.get("id") is not None else None
            if use["is_glob"]:
                if target is None or "module" not in target["inner"]:
                    raise ValueError(f"unsupported glob re-export {use['source']} in {module_path}")
                for gid in target["inner"]["module"]["items"]:
                    glob_child = self.index[str(gid)]
                    if glob_child["visibility"] == "public":
                        self.child(glob_child, module_path)
                return
            path = f"{module_path}::{use['name']}"
            if target is None:
                # A re-export of a foreign item: record the re-export itself.
                self.add(path, None, f"pub use {path} = {use['source']}")
                return
            self.item(target, path, None)
            return
        self.item(child, f"{module_path}::{child['name']}", None)

    def render(self, crate_name: str) -> list[Entry]:
        root = self.index[str(self.doc["root"])]
        self.collect(root, crate_name)
        self.item(root, crate_name, None)
        return self.entries

    def public_aliases(self) -> dict[str, str]:
        """Canonical path -> public path of this crate's items, after render."""
        out = {}
        for key, public in self.public.items():
            known = self.paths.get(key)
            if known and known["crate_id"] == 0:
                out["::".join(known["path"])] = public
        return out


