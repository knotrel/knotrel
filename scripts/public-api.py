@dataclass
class Inputs:
    """Everything the checks read besides the generated snapshots."""

    committed: dict[str, str]
    classification: str
    stability: str
    policy: str = ""
    crate_lints: dict[str, dict] = field(default_factory=dict)
    workspace_version: str = "0.0.0"
    # The base revision's classification, or None when there is none.
    base_classification: str | None = None


def run_checks(snapshots: list[Snapshot], inputs: Inputs) -> list[str]:
    """All checks on generated snapshots against committed files; returns errors."""
    errors = []
    items: dict[str, tuple[str | None, str | None]] = {}
    non_exhaustive: set[str] = set()
    for snapshot in snapshots:
        expected = render_file(snapshot)
        actual = inputs.committed.get(snapshot.crate)
        name = os.path.relpath(snapshot_file(snapshot.crate), ROOT)
        if actual is None:
            errors.append(f"{name} is missing; run `python3 scripts/public-api.py generate`")
        elif actual != expected:
            diff = "".join(
                difflib.unified_diff(
                    actual.splitlines(True), expected.splitlines(True), f"{name} (committed)", f"{name} (code)"
                )
            )
            errors.append(f"{name} differs from the code; run `python3 scripts/public-api.py generate`:\n{diff}")
        items.update(snapshot.items)
        non_exhaustive |= snapshot.non_exhaustive
    classes, class_errors = parse_classification(inputs.classification)
    errors += class_errors
    errors += check_classification(items, classes)
    rows, row_errors = parse_stability(inputs.stability)
    errors += row_errors
    errors += check_stability(rows, items, classes)
    policy, policy_errors = parse_policy(inputs.policy)
    errors += policy_errors
    errors += check_non_exhaustive(non_exhaustive, policy)
    base = None
    if inputs.base_classification is not None:
        base, base_errors = parse_classification(inputs.base_classification)
        errors += [f"base {error}" for error in base_errors]
    errors += check_narrowing(base, classes, policy)
    errors += check_semver_exceptions(policy, inputs.crate_lints, inputs.workspace_version)
    return errors


def read(path: str) -> str | None:
    try:
        with open(path, encoding="utf-8") as handle:
            return handle.read()
    except FileNotFoundError:
        return None


def git(*args: str) -> str | None:
    result = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True)
    return result.stdout if result.returncode == 0 else None


def base_classification(ref: str | None) -> tuple[str | None, str | None]:
    """The classification at the merge base with ``ref``; returns (text, problem).

    ``ref`` defaults to the pull request's base branch in GitHub Actions
    (``GITHUB_BASE_REF``), else ``origin/main``. A base without the file
    (before this check existed) has nothing to compare: (None, None).
    """
    if not ref:
        base_ref = os.environ.get("GITHUB_BASE_REF")
        ref = f"origin/{base_ref}" if base_ref else "origin/main"
    merge_base = git("merge-base", "HEAD", ref)
    if merge_base is None:
        return None, f"cannot resolve the base revision {ref!r} (fetch it, or pass --base)"
    rel = os.path.relpath(CLASSIFICATION, ROOT).replace(os.sep, "/")
    return git("show", f"{merge_base.strip()}:{rel}"), None


def crate_semver_lints() -> dict[str, dict]:
    out = {}
    for package, _, _ in CRATES:
        with open(os.path.join(ROOT, "crates", package, "Cargo.toml"), "rb") as handle:
            manifest = tomllib.load(handle)
        lints = manifest.get("package", {}).get("metadata", {}).get("cargo-semver-checks", {}).get("lints", {})
        if lints:
            out[package] = lints
    return out


def workspace_version() -> str:
    with open(os.path.join(ROOT, "Cargo.toml"), "rb") as handle:
        return tomllib.load(handle)["workspace"]["package"]["version"]


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("command", choices=["generate", "check"])
    parser.add_argument("--target-dir", help="cargo target directory (default: target/public-api)")
    parser.add_argument("--base", help="base revision for the narrowing check (default: GITHUB_BASE_REF or origin/main)")
    parser.add_argument("--no-base", action="store_true", help="skip the comparison with a base revision")
    args = parser.parse_args(argv)
    target_dir = args.target_dir or os.path.join(ROOT, "target", "public-api")
    snapshots = generate_all(target_dir)
    if args.command == "generate":
        for snapshot in snapshots:
            with open(snapshot_file(snapshot.crate), "w", encoding="utf-8") as handle:
                handle.write(render_file(snapshot))
            print(f"wrote {os.path.relpath(snapshot_file(snapshot.crate), ROOT)} ({len(snapshot.lines)} lines)")
    committed = {s.crate: read(snapshot_file(s.crate)) for s in snapshots}
    inputs = Inputs(
        committed={k: v for k, v in committed.items() if v is not None},
        classification=read(CLASSIFICATION) or "",
        stability=read(STABILITY) or "",
        policy=read(POLICY) or "",
        crate_lints=crate_semver_lints(),
        workspace_version=workspace_version(),
    )
    errors = []
    if not args.no_base:
        inputs.base_classification, problem = base_classification(args.base)
        if problem and os.environ.get("GITHUB_ACTIONS") == "true":
            errors.append(problem)
        elif problem:
            print(f"warning: {problem}; narrowing check skipped", file=sys.stderr)
        elif inputs.base_classification is None:
            print("note: the base has no classification file; narrowing check against the base skipped")
    errors += run_checks(snapshots, inputs)
    for error in errors:
        print(f"error: {error}", file=sys.stderr)
    if errors:
        print(f"{len(errors)} public API check(s) failed", file=sys.stderr)
        return 1
    count = sum(len(s.items) for s in snapshots)
    print(f"public API snapshot, classification, policy and stability.md agree ({count} classified keys)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
