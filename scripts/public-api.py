#!/usr/bin/env python3
"""Checked public Rust API snapshot and stability classification.

Implements maintainer decision 9 of the v1.0 contract freeze
(docs/releases/v1.0-contract-freeze-review.md, R11): the public API of
`knotrel-core` and `knotrel-server` is committed as a text snapshot, and every
public item carries an explicit, machine-checkable classification.

Three files are involved, all under docs/api/:

* ``public-api-<crate>.txt`` (generated): one line per public item and per
  non-blanket trait implementation, rendered from rustdoc JSON. Items that
  exist only with the ``test-support`` feature are prefixed with
  ``#[cfg(feature = "test-support")]``.
* ``public-api-classification.txt`` (maintained by hand): one line per named
  public item, ``<class> <path>``, where class is ``stable``, ``experimental``
  or ``internal``. Trait implementations are not named items; they share the
  class of the implementing type.
* ``docs/stability.md``: its two Rust tables are cross-checked against the
  classification (see ``check_stability``).

Subcommands:

* ``generate``: rebuild rustdoc JSON and rewrite the snapshots.
* ``check``: rebuild rustdoc JSON and fail if a snapshot differs from the
  code, if a public item has no classification (or a classification names no
  item), if a classification breaks a consistency rule, or if stability.md
  disagrees with the classification.

rustdoc JSON is an unstable rustdoc output. The script enables it on the
pinned workspace toolchain (rust-toolchain.toml) with ``RUSTC_BOOTSTRAP=1``,
for this one rustdoc invocation only, as cargo-semver-checks does; the
format version is checked so a toolchain change fails loudly instead of
producing a silently different snapshot. Only the standard library is used.
"""

