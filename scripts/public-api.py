# stability.md cross-check
# ---------------------------------------------------------------------------

SECTION = re.compile(r"^## Rust: `([a-z0-9-]+)`\s*$")
CODE = re.compile(r"`([^`]+)`")


def parse_stability(text: str) -> tuple[list[tuple[str, int, list[str], str]], list[str]]:
    """Reads the Rust tables of stability.md.

    Returns rows as (crate name, line number, names, class) and errors. In
    the Rust sections every table row names items in backticks in its first
    column and has exactly one class (Stable, Experimental or Internal) in
    its second.
    """
    rows = []
    errors = []
    crate = None
    for number, line in enumerate(text.splitlines(), 1):
        if line.startswith("## "):
            match = SECTION.match(line)
            crate = match.group(1).replace("-", "_") if match else None
            continue
        if crate is None or not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 2 or cells[0] in ("Item", "") or set(cells[0]) <= set("-: "):
            continue
        names = CODE.findall(cells[0])
        cls = cells[1].lower()
        if cls not in CLASSES:
            errors.append(f"stability.md:{number}: class must be exactly Stable, Experimental or Internal, got {cells[1]!r}")
            continue
        if not names:
            errors.append(f"stability.md:{number}: the Item column names no item in backticks")
            continue
        rows.append((crate, number, names, cls))
    if not rows:
        errors.append("stability.md: no Rust classification rows found")
    return rows, errors


def check_stability(rows, items: dict[str, tuple[str | None, str | None]], classes: dict[str, str]) -> list[str]:
    """stability.md agrees with the classification.

    A name is resolved inside its section's crate (``Graph::link`` means
    ``knotrel_core::Graph::link``); ``*`` matches within one path segment.
    Rules:

    * every name matches at least one public item (stale names fail);
    * an item's governing row is the one that names it exactly, else the
      most specific matching pattern; its class must equal the item's
      classification;
    * every crate-root item, and every member whose class differs from its
      parent's, has a governing row, so the document lists every exception.
      Trait implementations are classified only in the classification file
      (stability.md states the rule they follow).

    The classification file stays the source of truth: editing stability.md
    alone can only make this check fail, never satisfy a missing class.
    """
    errors = []
    governing: dict[str, tuple[int, int, str]] = {}  # path -> (specificity, line, class)
    for crate, number, names, cls in rows:
        for name in names:
            pattern = f"{crate}::{name}"
            if "*" in pattern:
                regex = re.compile("^" + re.escape(pattern).replace(r"\*", "[^:]*") + "$")
                matched = [p for p in items if not is_impl(p) and regex.match(p)]
                specificity = 1
            else:
                matched = [pattern] if pattern in items else []
                specificity = 2
            if not matched:
                errors.append(f"stability.md:{number}: `{name}` is not a public item of {crate}")
                continue
            for path in matched:
                previous = governing.get(path)
                if previous and previous[0] == specificity and previous[2] != cls:
                    errors.append(f"stability.md:{number}: `{path}` is also listed as {previous[2]} on line {previous[1]}")
                if previous is None or specificity > previous[0]:
                    governing[path] = (specificity, number, cls)
    for path, (_, number, cls) in sorted(governing.items()):
        if path in classes and classes[path] != cls:
            errors.append(f"stability.md:{number}: `{path}` is {cls.capitalize()} there but {classes[path]} in the classification")
    for path, (parent, _) in sorted(items.items()):
        cls = classes.get(path)
        if cls is None or is_impl(path):
            continue
        if parent is None and path not in governing:
            errors.append(f"stability.md does not list the crate-root item `{path}` ({cls})")
        elif parent is not None and parent in classes and classes[parent] != cls and path not in governing:
            errors.append(
                f"stability.md does not list `{path}`, which is {cls} while {parent} is {classes[parent]}"
            )
    return errors


