// @ts-check
/**
 * Generates src/api/generated/openapi.ts from ../docs/openapi.yaml with the pinned
 * openapi-typescript and Prettier versions. With --check, fails if the committed
 * file differs from a fresh generation (stale generated types) or if the
 * `knotrel.openapiSha256` digest in package.json does not identify the current
 * specification. The digest records which contract revision this console was
 * built and tested against.
 */
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import prettier from 'prettier';

const spec = new URL('../../docs/openapi.yaml', import.meta.url);
const target = fileURLToPath(new URL('../src/api/generated/openapi.ts', import.meta.url));
const header =
  '/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n';

const manifestPath = fileURLToPath(new URL('../package.json', import.meta.url));
const specText = (await readFile(spec, 'utf8')).replace(/\r\n/g, '\n');
const digest = createHash('sha256').update(specText).digest('hex');
const manifestText = await readFile(manifestPath, 'utf8');
const manifest = JSON.parse(manifestText);

const ast = await openapiTS(spec);
const options = (await prettier.resolveConfig(target)) ?? {};
const generated = await prettier.format(header + astToString(ast), {
  ...options,
  filepath: target,
});

if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current.replace(/\r\n/g, '\n') !== generated) {
    console.error(
      'src/api/generated/openapi.ts is stale. Run `npm run generate:api` and commit the result.',
    );
    process.exit(1);
  }
  if (manifest.knotrel?.openapiSha256 !== digest) {
    console.error(
      `package.json knotrel.openapiSha256 does not match docs/openapi.yaml (${digest}). Run \`npm run generate:api\`.`,
    );
    process.exit(1);
  }
  console.log(`Generated API types match docs/openapi.yaml (sha256 ${digest}).`);
} else {
  await writeFile(target, generated);
  manifest.knotrel = { ...manifest.knotrel, openapiSha256: digest };
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`Wrote ${target} and recorded OpenAPI sha256 ${digest}`);
}
